-- Adds user accounts and book ownership.
-- Safe to run more than once.

CREATE TABLE IF NOT EXISTS cashexpense_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_cashexpense_users_email ON cashexpense_users (email);

-- Owner of each book. Existing books stay NULL until the first account signs up and claims them.
ALTER TABLE cashexpense_books
    ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES cashexpense_users (id);

CREATE INDEX IF NOT EXISTS ix_cashexpense_books_user_id ON cashexpense_books (user_id);
